# CHAPTER 16: SENIOR BEHAVIORAL & LEADERSHIP (40-50% of the offer)
# Read as: VS Code (Markdown-in-Python) — a preparation workbook.
# At 10 YOE, technical skill gets you IN the room; behavioral and
# leadership signal decides your LEVEL and your NUMBER. Most
# down-levelling (and lost lakhs) happens here, not in SQL.
# ============================================================
"""
HOW TO USE THIS CHAPTER
-----------------------
Fill in the templates with YOUR real stories. Rehearse out loud and
time yourself (2-3 min per answer). Quantify every outcome. A vague
"improved performance" is a junior answer; "cut a 4-hour job to 6 min,
saving ~$4k/mo" is a senior one.
"""

# ============================================================
# SECTION 1: WHAT SENIOR/STAFF BEHAVIORAL ACTUALLY TESTS
# ------------------------------------------------------------
# Junior "tell me about a bug you fixed" becomes, at 10 YOE:
#   * INFLUENCE without authority (drove a decision across teams)
#   * AMBIGUITY (owned a vague problem end-to-end)
#   * IMPACT at scale (moved a business metric, quantified)
#   * JUDGEMENT / trade-offs (chose, and can defend the alternative)
#   * DISAGREEMENT (pushed back on a leader / PM with data)
#   * MENTORSHIP / multiplier effect (made others better)
#   * FAILURE + learning (owned it, no blame, changed behavior)
# Map each competency to 1-2 stories BEFORE the interview.
# ============================================================


# ============================================================
# SECTION 2: THE STAR-L FRAMEWORK (senior upgrade of STAR)
# ------------------------------------------------------------
# S - Situation  : 1-2 sentences of context + stakes ($ / scale).
# T - Task       : what YOU specifically owned (not "the team").
# A - Action     : the 2-3 decisions you made + why (show judgement).
# R - Result     : quantified outcome (%, ₹, time, adoption).
# L - Learning   : what you'd do differently / how it changed you.
# Keep A the longest. Interviewers score YOUR decisions, not the team's.
# ============================================================

STORY_TEMPLATE = """
COMPETENCY: <e.g. influence without authority>
S:
T:
A: (decision 1 + why) ... (decision 2 + why) ... (trade-off I weighed)
R: (metric moved: from X to Y, worth ₹___ / saved ___ hrs / ___% lift)
L:
"""


# ============================================================
# SECTION 3: 8 STORIES EVERY 10-YOE DA MUST HAVE READY
# ------------------------------------------------------------
STORY_BANK = """
1. BIGGEST BUSINESS IMPACT — an analysis that changed a decision and
   moved a metric. (Lead with the number.)
2. INFLUENCED A SENIOR STAKEHOLDER — you changed a VP/PM's direction
   with data they initially resisted.
3. AMBIGUOUS PROBLEM — "figure out why retention is down" with no
   clear starting point; how you scoped and structured it.
4. DISAGREEED WITH DATA — a metric/experiment said the popular idea
   was wrong; how you delivered the bad news and what happened.
5. FAILURE / WRONG ANALYSIS — a mistake that shipped, how you caught
   it, owned it, and prevented recurrence.
6. MENTORSHIP / MULTIPLIER — leveled up juniors, built a self-serve
   model, or set a standard the whole team adopted.
7. COMPETING PRIORITIES / SAID NO — pushed back on a low-value request
   to protect high-impact work; how you negotiated.
8. DRIVING STRATEGY — defined a North Star / metric framework / roadmap,
   not just answered tickets.
"""


# ============================================================
# SECTION 4: WORKED EXAMPLE (model the quantified senior answer)
# ------------------------------------------------------------
WORKED_EXAMPLE = """
COMPETENCY: Influence without authority + business impact

S: Our marketplace's GMV growth stalled for 2 quarters; leadership
   assumed the fix was more marketing spend (~₹2 Cr proposal).
T: I owned the diagnosis as lead analyst and had to recommend where
   to invest before the budget was locked.
A: I decomposed GMV = active buyers x orders/buyer x AOV and found
   growth was fine on acquisition but retention had dropped in one
   cohort. I traced it to a checkout change that raised failed
   payments 8%. Rather than just report it, I ran a DiD across the
   affected vs unaffected regions to prove causation (couldn't A/B
   retroactively), and quantified the recoverable GMV. I presented
   two options with trade-offs and recommended fixing payments over
   more spend, knowing it meant contradicting the marketing VP.
R: The payments fix recovered ~6% GMV in the affected cohort
   (~₹1.4 Cr annualized) at near-zero cost, and we redirected the
   ₹2 Cr marketing ask to a higher-ROI channel.
L: I learned to pair the finding with an identification strategy AND
   a recommendation — data alone doesn't move a room; a quantified,
   decision-ready recommendation does.
"""


# ============================================================
# SECTION 5: HANDLING THE HARD QUESTIONS (crisp scripts)
# ------------------------------------------------------------
HARD_QUESTIONS = """
"Why are you leaving / why us?"
  -> Growth + scope, not away-from-pain. Tie to their product/mission.
"Walk me through your resume."  (2 min MAX)
  -> Arc of increasing scope + impact; land on why THIS role is next.
"Tell me about a conflict."
  -> Pick a professional disagreement resolved with data + empathy;
     show you preserved the relationship. Never trash anyone.
"Weakness?"
  -> A real one + the SYSTEM you built to manage it. No humblebrag.
"Time you were wrong?"
  -> Own it fully, show the correction + the process change. This is
     a maturity test; deflecting fails it.
"Disagree with your manager?"
  -> Disagreed privately with data, committed once decided
     ('disagree and commit'). Shows spine + team-first.
"""


# ============================================================
# SECTION 6: QUESTIONS YOU ASK THEM (senior candidates interview back)
# ------------------------------------------------------------
ASK_THEM = """
* "What's your team's North Star metric and who owns it?"
* "How are analytics decisions made — do experiments actually change
   the roadmap, or is it opinion-led?"
* "Where does the analytics function sit — embedded, centralized, hybrid?"
* "What does success look like for this role at 6 and 12 months?"
* "What's the biggest data-trust or tooling gap you'd want me to fix?"
Great questions signal you operate at their level and are evaluating fit.
"""


# ============================================================
# SECTION 7: COMPENSATION NEGOTIATION (this section IS the 70-80 LPA)
# ------------------------------------------------------------
NEGOTIATION = """
The best technical prep is wasted if you under-negotiate. Rules:

1. NEVER give the first number. "I'm targeting a market-competitive
   package for a senior/staff analyst; what range is budgeted for
   this level?" Anchor on LEVEL, not your current salary.
2. Get LEVELLED right FIRST — comp follows level. Push to interview
   at the highest level you can defend; a level bump > any haggling.
3. Total comp, not base: base + bonus + ESOPs/RSUs + joining bonus +
   benefits. At product companies, equity is often 20-40% of the number.
4. Have COMPETING OFFERS or a credible market rate (levels.fyi,
   AmbitionBox, peer data). Leverage = alternatives.
5. When they make an offer, DON'T accept on the call. "Thank you —
   I'm excited. Let me review the full package and revert." Then make
   ONE well-reasoned counter, not many small ones.
6. Justify the counter with VALUE and market, not need. "Given the
   scope (owning the metrics layer + experimentation) and my 10 years
   driving X, I'd be aligned at ₹__; can we close the gap on base/equity?"
7. Negotiate the WHOLE package: if base is capped, push joining bonus,
   ESOP count, band, level, or an early review. Everything is a lever.

MINDSET: they've already decided they want you by the offer stage;
asking professionally does NOT rescind offers. Silence and a calm
counter are your strongest tools. This one conversation is often
worth 10-20 LPA — prepare for it like a technical round.
"""


