# ------------------------------------------------------------
CHECKLIST = """
[ ] 8 STAR-L stories written + rehearsed out loud, each < 3 min.
[ ] Every story has a QUANTIFIED result (%, ₹, time, adoption).
[ ] Researched their product, North Star, recent launches, competitors.
[ ] 5 sharp questions to ask each interviewer.
[ ] Your leveling + target total-comp range decided, with market data.
[ ] A 2-minute crisp "walk me through your background" arc.
[ ] One 'failure' and one 'conflict' story you can tell WITHOUT flinching.
"""


